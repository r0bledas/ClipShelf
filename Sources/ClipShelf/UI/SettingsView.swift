import AppKit
import Carbon
import ClipShelfCore
import SwiftUI

struct SettingsView: View {
    @ObservedObject var store: ClipboardStore

    var body: some View {
        TabView {
            generalTab
                .tabItem { Label("General", systemImage: "gearshape") }

            shortcutsTab
                .tabItem { Label("Shortcuts", systemImage: "command") }

            rulesTab
                .tabItem { Label("Rules", systemImage: "slider.horizontal.3") }
        }
        .padding(20)
        .frame(width: 500, height: 370)
    }

    // MARK: - General Tab

    private var generalTab: some View {
        Form {
            Section {
                Toggle("Open at Login", isOn: $store.settings.openAtLogin)
                Toggle("Show in Menu Bar", isOn: $store.settings.showInMenuBar)
                HStack {
                    Toggle("Sound Effects", isOn: $store.settings.soundEffectsEnabled)
                    Spacer()
                    Button("Preview") {
                        SoundEffectPlayer.shared.reload()
                        SoundEffectPlayer.shared.playCopy(enabled: true)
                    }
                    .controlSize(.small)
                }
            }

            Section {
                Picker("Keep History", selection: $store.settings.historyRetention) {
                    ForEach(HistoryRetention.allCases, id: \.self) { option in
                        Text(option.rawValue).tag(option)
                    }
                }
                .pickerStyle(.segmented)

                HStack {
                    Text("Pinned items are always kept.")
                        .font(.caption)
                        .foregroundStyle(.secondary)
                    Spacer()
                    Button("Clear History", role: .destructive) {
                        store.clearUnpinnedHistory()
                    }
                    .controlSize(.small)
                }
            }

            Section {
                VStack(alignment: .leading, spacing: 4) {
                    Text("Custom Sound Override")
                        .font(.caption.weight(.semibold))
                    Text("Drop Copy.aiff or Paste.aiff into ~/Library/Application Support/ClipShelf/Sounds/ to override built-in sounds.")
                        .font(.caption)
                        .foregroundStyle(.secondary)
                }
            }
        }
        .formStyle(.grouped)
    }

    // MARK: - Shortcuts Tab

    private var shortcutsTab: some View {
        Form {
            Section("Global Shortcuts") {
                HStack {
                    Text("Activate ClipShelf")
                    Spacer()
                    ShortcutRecorderButton(shortcut: $store.settings.activateShortcut)
                }

                HStack {
                    Spacer()
                    Button("Reset to Default (⇧⌘V)") {
                        store.settings.activateShortcut = .defaultActivate
                    }
                    .controlSize(.small)
                }
            }

            Section("Shelf Navigation") {
                LabeledContent("Search", value: "⌘F")
                LabeledContent("Quick Paste Slots", value: "⌘1 – ⌘9")
                LabeledContent("Paste Selected", value: "↩")
                LabeledContent("Paste as Plain Text", value: "⇧↩")
                LabeledContent("Quick Look Preview", value: "Space")
                LabeledContent("Delete Selected", value: "⌘⌫")
            }
        }
        .formStyle(.grouped)
    }

    // MARK: - Rules Tab

    private var rulesTab: some View {
        Form {
            Section("Content Filters") {
                Toggle(isOn: $store.settings.ignoreConfidential) {
                    VStack(alignment: .leading, spacing: 2) {
                        Text("Ignore confidential content")
                        Text("Do not save passwords and sensitive data when detected.")
                            .font(.caption)
                            .foregroundStyle(.secondary)
                    }
                }

                Toggle(isOn: $store.settings.ignoreTransient) {
                    VStack(alignment: .leading, spacing: 2) {
                        Text("Ignore transient content")
                        Text("Do not save temporary data generated by other apps.")
                            .font(.caption)
                            .foregroundStyle(.secondary)
                    }
                }

                Toggle(isOn: $store.settings.generateLinkPreviews) {
                    VStack(alignment: .leading, spacing: 2) {
                        Text("Generate link previews")
                        Text("Fetches page title and preview image; may trigger one-time or analytics-sensitive links.")
                            .font(.caption)
                            .foregroundStyle(.secondary)
                    }
                }
            }

            Section("Ignored Applications") {
                List {
                    ForEach(store.settings.ignoredApps) { app in
                        HStack {
                            if let icon = store.appIcon(for: app.bundleID) {
                                Image(nsImage: icon)
                                    .resizable()
                                    .frame(width: 18, height: 18)
                            }
                            Text(app.name)
                            Spacer()
                            Text(app.bundleID)
                                .font(.caption)
                                .foregroundStyle(.secondary)
                            Button {
                                store.settings.ignoredApps.removeAll(where: { $0.bundleID == app.bundleID })
                            } label: {
                                Image(systemName: "minus.circle.fill")
                                    .foregroundStyle(.secondary)
                            }
                            .buttonStyle(.plain)
                        }
                    }
                }
                .frame(height: 82)

                HStack {
                    Button("Add Application…") {
                        pickIgnoredApplication()
                    }
                    .controlSize(.small)
                    Spacer()
                }
            }
        }
        .formStyle(.grouped)
    }

    private func pickIgnoredApplication() {
        let panel = NSOpenPanel()
        panel.directoryURL = URL(fileURLWithPath: "/Applications")
        panel.allowedContentTypes = [.applicationBundle]
        panel.allowsMultipleSelection = false
        panel.canChooseDirectories = false
        guard panel.runModal() == .OK, let url = panel.url,
              let bundle = Bundle(url: url),
              let bundleID = bundle.bundleIdentifier else {
            return
        }
        let name = (bundle.object(forInfoDictionaryKey: "CFBundleDisplayName") as? String)
            ?? (bundle.object(forInfoDictionaryKey: "CFBundleName") as? String)
            ?? url.deletingPathExtension().lastPathComponent
        if !store.settings.ignoredApps.contains(where: { $0.bundleID == bundleID }) {
            store.settings.ignoredApps.append(IgnoredApp(bundleID: bundleID, name: name))
        }
    }
}

// MARK: - Interactive Shortcut Recorder

private struct ShortcutRecorderButton: View {
    @Binding var shortcut: ShortcutSpec
    @State private var isRecording = false
    @State private var monitor: Any?

    var body: some View {
        Button {
            if isRecording {
                stopRecording()
            } else {
                startRecording()
            }
        } label: {
            Text(isRecording ? "Press shortcut…" : shortcut.displayString)
                .font(.system(size: 12.5, weight: .medium, design: .rounded))
                .frame(minWidth: 110)
        }
        .buttonStyle(.bordered)
        .tint(isRecording ? .accentColor : nil)
        .onDisappear { stopRecording() }
    }

    private func startRecording() {
        isRecording = true
        monitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { event in
            if Int(event.keyCode) == kVK_Escape {
                stopRecording()
                return nil
            }

            let flags = event.modifierFlags.intersection(.deviceIndependentFlagsMask)
            var carbonMods: UInt32 = 0
            var symbols = ""
            if flags.contains(.control) { carbonMods |= UInt32(controlKey); symbols += "⌃" }
            if flags.contains(.option) { carbonMods |= UInt32(optionKey); symbols += "⌥" }
            if flags.contains(.shift) { carbonMods |= UInt32(shiftKey); symbols += "⇧" }
            if flags.contains(.command) { carbonMods |= UInt32(cmdKey); symbols += "⌘" }

            // Require at least one modifier key
            guard carbonMods != 0 else { return nil }

            let keyLabel = (event.charactersIgnoringModifiers ?? "").uppercased()
            guard !keyLabel.isEmpty else { return nil }

            shortcut = ShortcutSpec(
                keyCode: UInt32(event.keyCode),
                modifiers: carbonMods,
                displayString: symbols + keyLabel
            )
            stopRecording()
            return nil
        }
    }

    private func stopRecording() {
        isRecording = false
        if let monitor {
            NSEvent.removeMonitor(monitor)
            self.monitor = nil
        }
    }
}
